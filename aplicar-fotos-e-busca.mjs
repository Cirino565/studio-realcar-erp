/** Escreve o arquivo respeitando a quebra de linha que o projeto ja usa. */
function escreverPreservandoQuebra(caminho, conteudoNovo) {
  const atual = readFileSync(caminho, "utf8");
  const usaCRLF = atual.includes("\r\n");
  const normalizado = conteudoNovo.replace(/\r\n/g, "\n");
  const saida = usaCRLF ? normalizado.replace(/\n/g, "\r\n") : normalizado;

  if (atual === saida) return false;

  writeFileSync(caminho, saida, "utf8");
  return true;
}

