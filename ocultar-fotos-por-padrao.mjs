function decodificar(base64) {
  return Buffer.from(base64, "base64").toString("utf-8");
}

function aplicar(caminho, novoConteudoB64, rotulo) {
  if (!existsSync(caminho)) {
    console.log(`[erro] Nao encontrei o arquivo: ${caminho}`);
    process.exitCode = 1;
    return;
  }

  const atual = readFileSync(caminho, "utf-8");
  const novo = decodificar(novoConteudoB64);

  if (atual === novo) {
    console.log(`[pulou] ${rotulo} ja esta atualizado.`);
    return;
  }

  writeFileSync(caminho, novo, "utf-8");
  console.log(`[ok] ${rotulo} atualizado.`);
}

